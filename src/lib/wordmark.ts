export function wordmark(text: string): string {
  const rows = ['', '', '', '', '', ''];
  for (const ch of text.toUpperCase()) {
    const g = G[ch] ?? G['.'].map((r) => r.replace(/./g, ' '));
    g.forEach((line, i) => (rows[i] += line));
  }
  return rows.map((r) => r.replace(/\s+$/, '')).join('\n');
}
